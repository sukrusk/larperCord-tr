pub const VARIANT = extern struct {
    vt: u16 = 0,
    wReserved1: u16 = 0,
    wReserved2: u16 = 0,
    wReserved3: u16 = 0,
    data: extern union {
        ulVal: u32,
        boolVal: i16,
        pad: [2]u64,
    } = .{ .pad = .{ 0, 0 } },

    pub fn fromBool(v: bool) VARIANT {
        return .{ .vt = 11, .data = .{ .boolVal = if (v) -1 else 0 } };
    }

    pub fn fromU32(v: u32) VARIANT {
        return .{ .vt = 19, .data = .{ .ulVal = v } };
    }
};

pub const IUnknown = extern struct {
    lpVtbl: *const extern struct {
        QueryInterface: *const fn (*IUnknown, *const GUID, *?*anyopaque) callconv(.winapi) HRESULT,
        AddRef: *const fn (*IUnknown) callconv(.winapi) ULONG,
        Release: *const fn (*IUnknown) callconv(.winapi) ULONG,
    },
};

pub fn release(ptr: anytype) void {
    const info = @typeInfo(@TypeOf(ptr));
    if (info == .optional) {
        if (ptr) |p| _ = @as(*IUnknown, @ptrCast(@alignCast(p))).lpVtbl.Release(@ptrCast(@alignCast(p)));
    } else {
        _ = @as(*IUnknown, @ptrCast(@alignCast(ptr))).lpVtbl.Release(@ptrCast(@alignCast(ptr)));
    }
}

pub fn queryInterface(ptr: anytype, comptime T: type, iid: *const GUID) ?*T {
    var out: ?*anyopaque = null;
    const u: *IUnknown = @ptrCast(@alignCast(ptr));
    if (!succeeded(u.lpVtbl.QueryInterface(u, iid, &out))) return null;
    return @ptrCast(@alignCast(out));
}

pub fn slot(obj: anytype, comptime idx: usize, comptime Fn: type) Fn {
    const table: [*]const *const anyopaque = @as(*const [*]const *const anyopaque, @ptrCast(@alignCast(obj))).*;
    return @ptrCast(@alignCast(table[idx]));
}
