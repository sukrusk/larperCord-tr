pub fn fcc(chars: *const [4]u8) u32 {
    return @as(u32, chars[0]) | (@as(u32, chars[1]) << 8) | (@as(u32, chars[2]) << 16) | (@as(u32, chars[3]) << 24);
}

pub fn mfGuid(fourcc: *const [4]u8) GUID {
    return GUID.init(fcc(fourcc), 0x0000, 0x0010, .{ 0x80, 0x00, 0x00, 0xAA, 0x00, 0x38, 0x9B, 0x71 });
}

